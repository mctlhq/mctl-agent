const (
	// Owner is the only GitHub org a draft may target.
	Owner = "mctlhq"
	// Label is the only label ever applied.
	Label = "spike:scout"

	maxTitleRunes = 256
	maxBodyBytes  = 60000
	searchPerPage = 100
	searchMaxPage = 10
	memoTTL       = 10 * time.Minute
	searchQuery   = `org:mctlhq is:issue label:"spike:scout"`
)

// Scaffold is the static spike-section block of a scout draft, byte for byte
// mctl-agents orchestrator/scout/render.py SPIKE_SECTIONS as draft_body joins
// it. mctl-agents wins if the two ever differ; TestScaffoldMatchesPython pins
// the Python output. Drafts carry it here rather than in the button URL
// because ten URLs with it exceed Telegram's reply-markup limit.
const Scaffold = "\n\n## Existing / duplicate check\n- Verify Related against current issues/code; reuse an existing owner, no parity-only capability." +
	"\n\n## Required experiment\n- Smallest bounded experiment that can falsify the question, on current MCTL workload, not vendor claims." +
	"\n\n## Measurements\n- Baseline vs candidate: success, cost, latency, reliability. unknown is not zero." +
	"\n\n## Invariants\n- No rollout or authority expansion; identity/policy/approval boundaries stay authoritative." +
	"\n\n## Deliverables\n- Duplicate map, experiment evidence, follow-ups for proven gaps, one recommendation from Outcomes." +
	"\n\n## Non-goals\n- Implementation before the decision; new epic/runtime for parity only."

const (
	scaffoldMarker = "## Existing / duplicate check"
	generatedLine  = "\n\nGenerated by mctl-agents scout"
)

// WithScaffold returns body with Scaffold inserted before the trailing
// "Generated by mctl-agents scout" line, or appended when there is none.
// A body that already has the first section heading is returned unchanged,
// so drafts from scouts that still ship the scaffold are not doubled.
func WithScaffold(body string) string {
	if strings.HasPrefix(body, scaffoldMarker) || strings.Contains(body, "\n"+scaffoldMarker) {
		return body
	}
	if i := strings.LastIndex(body, generatedLine); i >= 0 {
		return body[:i] + Scaffold + body[i:]
	}
	return strings.TrimRight(body, "\n") + Scaffold
}

// Errors map one-to-one onto the short feedback texts of the callback.
var (
	ErrDraftNotFound     = errors.New("draft not found")
	ErrTargetNotAllowed  = errors.New("draft target not allowed")
	ErrDraftRejected     = errors.New("draft rejected")
	ErrRepoNotAccessible = errors.New("repo not accessible")
	ErrSearchFailed      = errors.New("could not check for duplicates")
	ErrCreateFailed      = errors.New("create failed")
)

// pyWS / pyNonWS are Python's str-mode \s / \S, so SourceOf matches
// mctl-agents' _SOURCE_RE = r"^Source:\s*(\S+)" (re.MULTILINE).
const (
	pyWSChars = `\t\n\x0b\f\r\x1c-\x20\x{85}\x{a0}\x{1680}\x{2000}-\x{200a}\x{2028}\x{2029}\x{202f}\x{205f}\x{3000}`
	pyWS      = `[` + pyWSChars + `]`
	pyNonWS   = `[^` + pyWSChars + `]`
)

var (
	callbackRe = regexp.MustCompile(`^scout:create:([1-9][0-9]?)$`)
	sourceRe   = regexp.MustCompile(`(?m)^Source:` + pyWS + `*(` + pyNonWS + `+)`)
	repoNameRe = regexp.MustCompile(`^[A-Za-z0-9._-]+$`)
)

// ParseCallbackData parses "scout:create:N" with N in 1..99.
func ParseCallbackData(s string) (int, bool) {
	m := callbackRe.FindStringSubmatch(s)
	if m == nil {
		return 0, false
	}
	n, err := strconv.Atoi(m[1])
	return n, err == nil
}

// ValidRepoName reports whether name is an acceptable allowlist entry.
func ValidRepoName(name string) bool {
	return repoNameRe.MatchString(name) && name != "." && name != ".."
}

// FindDraft returns the row and URL of the single "Draft spike N" URL button.
func FindDraft(markup notify.InlineKeyboardMarkup, n int) (int, string, error) {
	want := "Draft spike " + strconv.Itoa(n)
	row, rawURL, found := -1, "", 0
	for i, r := range markup.InlineKeyboard {
		for _, b := range r {
			if strings.TrimSpace(b.Text) == want && b.URL != "" {
				row, rawURL = i, b.URL
				found++
			}
		}
	}
	if found != 1 {
		return 0, "", ErrDraftNotFound
	}
	return row, rawURL, nil
}

// Draft is a parsed, validated issue draft.
type Draft struct {
	Repo   string
	Title  string
	Body   string
	Labels []string
	Source string // normalised
	// LabelsOverridden is set when the draft asked for labels other than
	// exactly spike:scout; they are ignored either way.
	LabelsOverridden bool
}

// ParseDraft validates a GitHub issues/new URL against the repo allowlist.
// The draft's own labels are ignored: Labels is always exactly [spike:scout].
// Body gets the spike scaffold (WithScaffold) when the URL left it out.
func ParseDraft(rawURL string, allowedRepos map[string]bool) (Draft, error) {
	u, err := url.Parse(rawURL)
	if err != nil || u.Scheme != "https" || u.Host != "github.com" || u.User != nil || u.Opaque != "" {
		return Draft{}, ErrTargetNotAllowed
	}
	parts := strings.Split(u.EscapedPath(), "/")
	if len(parts) != 5 || parts[0] != "" || parts[1] != Owner || parts[3] != "issues" || parts[4] != "new" {
		return Draft{}, ErrTargetNotAllowed
	}
	repo := parts[2]
	if !ValidRepoName(repo) || !allowedRepos[repo] {
		return Draft{}, ErrTargetNotAllowed
	}
	q := u.Query()
	title := strings.TrimSpace(q.Get("title"))
	body := q.Get("body")
	if !strings.HasPrefix(title, "spike:") || utf8.RuneCountInString(title) > maxTitleRunes || len(body) > maxBodyBytes {
		return Draft{}, ErrDraftRejected
	}
	src := SourceOf(body)
	if src == "" {
		return Draft{}, ErrDraftRejected
	}
	lbl := q.Get("labels")
	return Draft{
		Repo: repo, Title: title, Body: WithScaffold(body), Labels: []string{Label}, Source: NormaliseURL(src),
		LabelsOverridden: lbl != "" && lbl != Label,
	}, nil
}

// SourceOf returns the first "Source:" value of body, or "".
func SourceOf(body string) string {
	m := sourceRe.FindStringSubmatch(body)
	if m == nil {
		return ""
	}
	return m[1]
}

// NormaliseURL canonicalises a source URL for duplicate detection. It is an
// exact port of mctl-agents orchestrator/scout/dedupe.py normalise_url
// (CPython 3.12 urllib.parse semantics): both sides must compute the same key
// or a duplicate goes unnoticed. mctl-agents wins if the two ever differ;
// TestNormaliseURLMatchesPython pins vectors generated by running the Python.
//
//	parts = urlsplit(url.strip())
//	query = [(k, v) for k, v in parse_qsl(parts.query, keep_blank_values=True)
//	         if not (k.startswith(("utm_", "mc_")) or k in {"ref", "fbclid", "gclid"})]
//	return urlunsplit((scheme.lower(), netloc.lower(), path.rstrip("/"), urlencode(query), ""))
//
// Python raises ValueError on a few malformed netlocs (unbalanced IPv6
// brackets); such a URL never reaches a scout draft, so no special case here.
// strings.ToLower matches str.lower for every ASCII and ordinary Unicode host.
func NormaliseURL(s string) string {
	scheme, netloc, path, query := pyURLSplit(strings.TrimFunc(s, pyIsSpace))
	var kept []string
	for _, kv := range pyParseQSL(query) {
		k := kv[0]
		if strings.HasPrefix(k, "utm_") || strings.HasPrefix(k, "mc_") || k == "ref" || k == "fbclid" || k == "gclid" {
			continue
		}
		kept = append(kept, pyQuotePlus(k)+"="+pyQuotePlus(kv[1]))
	}
	return pyURLUnsplit(strings.ToLower(scheme), strings.ToLower(netloc), strings.TrimRight(path, "/"), strings.Join(kept, "&"))
}

// pyIsSpace is Python's str.isspace (also what re's \s matches in str mode).
func pyIsSpace(r rune) bool {
	switch {
	case r >= 0x09 && r <= 0x0d, r >= 0x1c && r <= 0x20, r == 0x85, r == 0xa0, r == 0x1680,
		r >= 0x2000 && r <= 0x200a, r == 0x2028, r == 0x2029, r == 0x202f, r == 0x205f, r == 0x3000:
		return true
	}
	return false
}

var pyUsesNetloc = map[string]bool{
	"": true, "ftp": true, "http": true, "gopher": true, "nntp": true, "telnet": true,
	"imap": true, "wais": true, "file": true, "mms": true, "https": true, "shttp": true,
	"snews": true, "prospero": true, "rtsp": true, "rtspu": true, "rsync": true,
	"svn": true, "svn+ssh": true, "sftp": true, "nfs": true, "git": true, "git+ssh": true,
	"ws": true, "wss": true,
}

func isSchemeChar(c byte) bool {
	return c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' || c == '+' || c == '-' || c == '.'
}

// pyURLSplit is urllib.parse.urlsplit (3.12) minus the fragment, which
// normalise_url discards.
func pyURLSplit(u string) (scheme, netloc, path, query string) {
	u = strings.TrimLeftFunc(u, func(r rune) bool { return r <= 0x20 })
	u = strings.NewReplacer("\t", "", "\r", "", "\n", "").Replace(u)
	if i := strings.IndexByte(u, ':'); i > 0 && (u[0] >= 'a' && u[0] <= 'z' || u[0] >= 'A' && u[0] <= 'Z') {
		ok := true
		for j := 0; j < i; j++ {
			if !isSchemeChar(u[j]) {
				ok = false
				break
			}
		}
		if ok {
			scheme, u = strings.ToLower(u[:i]), u[i+1:]
		}
	}
	if strings.HasPrefix(u, "//") {
		end := len(u)
		if d := strings.IndexAny(u[2:], "/?#"); d >= 0 {
			end = d + 2
		}
		netloc, u = u[2:end], u[end:]
	}
	if i := strings.IndexByte(u, '#'); i >= 0 {
		u = u[:i]
	}
	if i := strings.IndexByte(u, '?'); i >= 0 {
		u, query = u[:i], u[i+1:]
	}
	return scheme, netloc, u, query
}

// pyURLUnsplit is urllib.parse.urlunsplit (3.12) with an empty fragment.
func pyURLUnsplit(scheme, netloc, path, query string) string {
	if netloc != "" || (scheme != "" && pyUsesNetloc[scheme] && !strings.HasPrefix(path, "//")) {
		if path != "" && path[0] != '/' {
			path = "/" + path
		}
		path = "//" + netloc + path
	}
	if scheme != "" {
		path = scheme + ":" + path
	}
	if query != "" {
		path += "?" + query
	}
	return path
}

// pyParseQSL is parse_qsl(qs, keep_blank_values=True): split on "&" only,
// skip empty fields, "+" means space, percent-decoding as unquote.
func pyParseQSL(qs string) [][2]string {
	var out [][2]string
	for _, f := range strings.Split(qs, "&") {
		if f == "" {
			continue
		}
		k, v, _ := strings.Cut(f, "=")
		out = append(out, [2]string{pyUnquote(strings.ReplaceAll(k, "+", " ")), pyUnquote(strings.ReplaceAll(v, "+", " "))})
	}
	return out
}

func unhex(c byte) (byte, bool) {
	switch {
	case c >= '0' && c <= '9':
		return c - '0', true
	case c >= 'a' && c <= 'f':
		return c - 'a' + 10, true
	case c >= 'A' && c <= 'F':
		return c - 'A' + 10, true
	}
	return 0, false
}

// pyUnquote is unquote(s, errors="replace"): each run of ASCII characters
// is percent-decoded to bytes and decoded as UTF-8 with U+FFFD for every
// maximal invalid subpart; non-ASCII characters pass through untouched.
// Invalid escapes stay literal.
func pyUnquote(s string) string {
	if !strings.Contains(s, "%") {
		return s
	}
	var out strings.Builder
	var buf []byte
	flush := func() {
		out.WriteString(decodeUTF8Replace(buf))
		buf = buf[:0]
	}
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c >= 0x80 {
			flush()
			out.WriteByte(c)
			continue
		}
		if c == '%' && i+2 < len(s) {
			if h, ok1 := unhex(s[i+1]); ok1 {
				if l, ok2 := unhex(s[i+2]); ok2 {
					buf = append(buf, h<<4|l)
					i += 2
					continue
				}
			}
		}
		buf = append(buf, c)
	}
	flush()
	return out.String()
}

// decodeUTF8Replace decodes b like Python's bytes.decode("utf-8", "replace"):
// one U+FFFD per maximal subpart of an ill-formed sequence.
func decodeUTF8Replace(b []byte) string {
	var out strings.Builder
	for len(b) > 0 {
		r, n := utf8.DecodeRune(b)
		if r != utf8.RuneError || n > 1 {
			out.WriteRune(r)
			b = b[n:]
			continue
		}
		out.WriteRune(utf8.RuneError)
		b = b[invalidPrefixLen(b):]
	}
	return out.String()
}

func invalidPrefixLen(b []byte) int {
	need, lo, hi := 0, byte(0x80), byte(0xbf)
	switch c := b[0]; {
	case c >= 0xc2 && c <= 0xdf:
		need = 1
	case c == 0xe0:
		need, lo = 2, 0xa0
	case c == 0xed:
		need, hi = 2, 0x9f
	case c >= 0xe1 && c <= 0xef:
		need = 2
	case c == 0xf0:
		need, lo = 3, 0x90
	case c == 0xf4:
		need, hi = 3, 0x8f
	case c >= 0xf1 && c <= 0xf3:
		need = 3
	default:
		return 1
	}
	n := 1
	for n <= need && n < len(b) {
		if b[n] < lo || b[n] > hi {
			break
		}
		lo, hi = 0x80, 0xbf
		n++
	}
	return n
}

// pyQuotePlus is quote_plus(s): UTF-8 bytes, unreserved = ALPHA DIGIT
// "_.-~", space becomes "+", everything else %XX upper-case.
func pyQuotePlus(s string) string {
	const hexd = "0123456789ABCDEF"
	var out strings.Builder
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c >= 'a' && c <= 'z', c >= 'A' && c <= 'Z', c >= '0' && c <= '9', c == '_', c == '.', c == '-', c == '~':
			out.WriteByte(c)
		case c == ' ':
			out.WriteByte('+')
		default:
			out.WriteByte('%')
			out.WriteByte(hexd[c>>4])
			out.WriteByte(hexd[c&15])
		}
	}
	return out.String()
}

// GitHub is the subset of the GitHub fixer this package needs. The owner is
// passed explicitly and is always Owner, so the draft target, the duplicate
// search (org:mctlhq) and the created issue can never name different orgs,
// whatever GITHUB_OWNER the fixer was built with.
type GitHub interface {
	RepoAccessible(ctx context.Context, owner, repo string) (int, error)
	SearchIssues(ctx context.Context, query string, page int) (*github.IssuesSearchResult, error)
	CreateIssue(ctx context.Context, owner, repo, title, body string, labels []string) (int, string, error)
}

// Result describes the issue a press resolved to.
type Result struct {
	Repo    string
	Number  int
	HTMLURL string
	Existed bool
	Row     int // keyboard row that held the draft button
}

// entry serialises presses for one normalised Source. refs counts callers
// that hold or wait for mu; it is guarded by Service.mu, and an entry is only
// evicted while refs is zero, so an in-flight press can never lose its entry
// to a press on another source.
type entry struct {
	mu      sync.Mutex
	refs    int // guarded by Service.mu
	created *Result
	expires time.Time
}

// Service creates spike issues from drafts.
type Service struct {
	gh      GitHub
	repos   map[string]bool
	now     func() time.Time
	mu      sync.Mutex
	entries map[string]*entry
}

// NewService builds a Service. An empty repo list disables it.
func NewService(gh GitHub, repos []string) *Service {
	m := map[string]bool{}
	for _, r := range repos {
		if ValidRepoName(r) {
			m[r] = true
		}
	}
	return &Service{gh: gh, repos: m, now: time.Now, entries: map[string]*entry{}}
}

// Enabled reports whether any repo is allowlisted.
func (s *Service) Enabled() bool { return s != nil && s.gh != nil && len(s.repos) > 0 }

// RepoCount is the size of the repo allowlist.
func (s *Service) RepoCount() int {
	if s == nil {
		return 0
	}
	return len(s.repos)
}

// entryFor returns the entry for key with a reference taken; the caller
// must pass it to release. Idle entries (no references) with no live memo
// are evicted here. Reading created/expires of an idle entry is race-free:
// its last user wrote them under e.mu before dropping its reference under
// s.mu, which this goroutine now holds.
func (s *Service) entryFor(key string) *entry {
	s.mu.Lock()
	defer s.mu.Unlock()
	now := s.now()
	for k, e := range s.entries {
		if k != key && e.refs == 0 && (e.created == nil || now.After(e.expires)) {
			delete(s.entries, k)
		}
	}
	e, ok := s.entries[key]
	if !ok {
		e = &entry{}
		s.entries[key] = e
	}
	e.refs++
	return e
}

func (s *Service) release(e *entry) {
	s.mu.Lock()
	e.refs--
	s.mu.Unlock()
}

// Create resolves press n on markup to an issue, creating it only when no
// issue with the same Source exists. Any failure to observe duplicates
// creates nothing.
func (s *Service) Create(ctx context.Context, markup notify.InlineKeyboardMarkup, n int) (Result, error) {
	if !s.Enabled() {
		return Result{}, ErrTargetNotAllowed
	}
	row, rawURL, err := FindDraft(markup, n)
	if err != nil {
		return Result{}, err
	}
	d, err := ParseDraft(rawURL, s.repos)
	if err != nil {
		return Result{}, err
	}

	if d.LabelsOverridden {
		slog.Info("scout spike draft labels ignored", "labels_overridden", true, "label", Label)
	}

	e := s.entryFor(d.Source)
	defer s.release(e) // runs after the Unlock below
	e.mu.Lock()
	defer e.mu.Unlock()

	if e.created != nil && s.now().Before(e.expires) {
		r := *e.created
		r.Existed, r.Row = true, row
		return r, nil
	}

	if code, err := s.gh.RepoAccessible(ctx, Owner, d.Repo); err != nil || code != http.StatusOK {
		return Result{}, ErrRepoNotAccessible
	}

	found, err := s.findExisting(ctx, d.Source)
	if err != nil {
		return Result{}, err
	}
	if found != nil {
		// Memoise like a created issue: a repeat press must not spend
		// another full search, nor depend on the search still seeing it.
		memo := *found
		e.created, e.expires = &memo, s.now().Add(memoTTL)
		found.Row = row
		return *found, nil
	}

	num, htmlURL, err := s.gh.CreateIssue(ctx, Owner, d.Repo, d.Title, d.Body, d.Labels)
	if err != nil {
		return Result{}, ErrCreateFailed
	}
	res := Result{Repo: d.Repo, Number: num, HTMLURL: htmlURL, Row: row}
	memo := res
	e.created, e.expires = &memo, s.now().Add(memoTTL)
	return res, nil
}

// findExisting searches every spike:scout issue (any state). Anything short
// of a complete, successful search is ErrSearchFailed.
func (s *Service) findExisting(ctx context.Context, source string) (*Result, error) {
	for page := 1; page <= searchMaxPage; page++ {
		res, err := s.gh.SearchIssues(ctx, searchQuery, page)
		if err != nil || res == nil || res.Total == nil || res.GetIncompleteResults() {
			return nil, ErrSearchFailed // a body without total_count is malformed
		}
		for _, is := range res.Issues {
			src := SourceOf(is.GetBody())
			if src == "" || NormaliseURL(src) != source {
				continue
			}
			return &Result{
				Repo:    repoOf(is),
				Number:  is.GetNumber(),
				HTMLURL: is.GetHTMLURL(),
				Existed: true,
			}, nil
		}
		if page*searchPerPage >= res.GetTotal() {
			return nil, nil // every result the search reported has been seen
		}
		if len(res.Issues) < searchPerPage {
			// A short page while total_count says more exist: the rest
			// could not be observed, which is not the same as absent.
			return nil, ErrSearchFailed
		}
	}
	return nil, ErrSearchFailed
}

func repoOf(is *github.Issue) string {
	if r := is.GetRepository(); r != nil && r.GetName() != "" {
		return r.GetName()
	}
	// repository_url ends in /repos/<owner>/<repo>.
	u := is.GetRepositoryURL()
	return u[strings.LastIndex(u, "/")+1:]
}
