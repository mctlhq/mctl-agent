type fakeGH struct {
	mu        sync.Mutex
	repoCode  int
	search    func(page int) (*github.IssuesSearchResult, error)
	creates   int
	searches  int
	createdAt []string
	bodies    []string
	owners    []string
}

func (f *fakeGH) RepoAccessible(_ context.Context, owner, _ string) (int, error) {
	f.mu.Lock()
	f.owners = append(f.owners, owner)
	f.mu.Unlock()
	if f.repoCode == 0 {
		return http.StatusOK, nil
	}
	return f.repoCode, nil
}
func (f *fakeGH) SearchIssues(_ context.Context, _ string, page int) (*github.IssuesSearchResult, error) {
	f.mu.Lock()
	f.searches++
	f.mu.Unlock()
	if f.search == nil {
		return &github.IssuesSearchResult{Total: github.Ptr(0)}, nil
	}
	return f.search(page)
}
func (f *fakeGH) CreateIssue(_ context.Context, owner, repo, _, body string, labels []string) (int, string, error) {
	f.mu.Lock()
	defer f.mu.Unlock()
	f.creates++
	f.bodies = append(f.bodies, body)
	f.owners = append(f.owners, owner)
	f.createdAt = append(f.createdAt, repo+":"+strings.Join(labels, ","))
	return 7, "https://github.com/mctlhq/" + repo + "/issues/7", nil
}

