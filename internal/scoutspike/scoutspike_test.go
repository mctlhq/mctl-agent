func TestCreateDoubleTapCreatesOnce(t *testing.T) {
	// Pins the per-source guard: search lag (always empty) must not allow a
	// second create. The fake search is a barrier: each caller waits until
	// both have entered (or a timeout), so without the per-source lock both
	// presses are provably inside the search at once and both create.
	var mu sync.Mutex
	entered := 0
	both := make(chan struct{})
	gh := &fakeGH{}
	gh.search = func(int) (*github.IssuesSearchResult, error) {
		mu.Lock()
		entered++
		if entered == 2 {
			close(both)
		}
		mu.Unlock()
		select {
		case <-both:
		case <-time.After(300 * time.Millisecond):
		}
		return &github.IssuesSearchResult{Total: github.Ptr(0)}, nil
	}
	svc := NewService(gh, []string{"mctl-api"})
	var wg sync.WaitGroup
	results := make([]Result, 2)
	for i := range results {
		wg.Add(1)
		go func(i int) {
			defer wg.Done()
			r, err := svc.Create(context.Background(), testMarkup(), 1)
			if err != nil {
				t.Error(err)
			}
			results[i] = r
		}(i)
	}
	wg.Wait()
	if gh.creates != 1 || gh.searches != 1 || gh.createdAt[0] != "mctl-api:spike:scout" {
		t.Fatalf("creates=%d searches=%d %v", gh.creates, gh.searches, gh.createdAt)
	}
	if results[0].Existed == results[1].Existed {
		t.Fatalf("exactly one call should create: %+v", results)
	}
}

func TestEntryForNeverEvictsReferencedEntry(t *testing.T) {
	// Pins agy F1: an entry handed to a press that has not locked it yet (or
	// is queued behind a failed press) must survive presses on other sources.
	svc := NewService(&fakeGH{}, []string{"mctl-api"})
	a := svc.entryFor("https://a.example/p") // in flight, created == nil
	b := svc.entryFor("https://b.example/q")
	svc.release(b)
	if again := svc.entryFor("https://a.example/p"); again != a {
		t.Fatal("in-flight entry was evicted; a concurrent press would get its own entry")
	}
	svc.release(a)
	svc.release(a)
	// Once idle and without a memo it is evictable again.
	svc.release(svc.entryFor("https://b.example/q"))
	svc.mu.Lock()
	_, kept := svc.entries["https://a.example/p"]
	svc.mu.Unlock()
	if kept {
		t.Fatal("idle entry without memo should be evicted")
	}
}

